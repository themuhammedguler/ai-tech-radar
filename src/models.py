"""
Data models and typed structures for the AI & Tech Radar pipeline (v4.0).
Enforces strict schema validation, immutability, and typing across all 4 sources and AI summaries.
"""

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from pathlib import Path
from typing import Optional


class SourceStatus(str, Enum):
    """Health and execution status for a data collector or processor."""
    SUCCESS = "SUCCESS"
    DEGRADED = "DEGRADED"
    FAILED = "FAILED"
    EMPTY = "EMPTY"
    SKIPPED = "SKIPPED"


@dataclass(frozen=True)
class TrendItem:
    """Immutable data model representing a curated technology news item (HackerNews)."""
    title: str
    url: str
    hn_url: str
    points: int
    comments: int
    category: str = "⚡ Teknoloji"
    tech_score: int = 0
    ranking_score: float = 0.0

    def __post_init__(self):
        if not self.title or not self.title.strip():
            raise ValueError("TrendItem title cannot be empty.")
        if not self.url or not self.url.startswith(("http://", "https://")):
            raise ValueError(f"Invalid URL for TrendItem: {self.url}")
        if self.points < 0 or self.comments < 0:
            raise ValueError("Points and comments must be non-negative integers.")


@dataclass(frozen=True)
class GithubRepoItem:
    """Immutable data model representing a trending GitHub open-source repository."""
    name: str
    url: str
    description: str
    language: str
    stars: int
    forks: int
    topics: list[str] = field(default_factory=list)

    def __post_init__(self):
        if not self.name or not self.name.strip():
            raise ValueError("GithubRepoItem name cannot be empty.")
        if not self.url or not self.url.startswith(("http://", "https://")):
            raise ValueError(f"Invalid URL for GithubRepoItem: {self.url}")
        if self.stars < 0 or self.forks < 0:
            raise ValueError("Stars and forks must be non-negative integers.")


@dataclass(frozen=True)
class HuggingFacePaperItem:
    """Immutable data model representing a community-upvoted Hugging Face daily paper."""
    title: str
    url: str
    authors: str
    upvotes: int
    num_comments: int
    summary: str
    published_date: str = field(default_factory=lambda: datetime.now().strftime("%Y-%m-%d"))

    def __post_init__(self):
        if not self.title or not self.title.strip():
            raise ValueError("HuggingFacePaperItem title cannot be empty.")
        if not self.url or not self.url.startswith(("http://", "https://")):
            raise ValueError(f"Invalid URL for HuggingFacePaperItem: {self.url}")
        if self.upvotes < 0 or self.num_comments < 0:
            raise ValueError("Upvotes and comments must be non-negative integers.")


@dataclass(frozen=True)
class ArxivPaper:
    """Immutable data model representing an academic research paper."""
    title: str
    summary: str
    link: str
    authors: str
    category: str = "cs.AI"
    published_date: str = field(default_factory=lambda: datetime.now().strftime("%Y-%m-%d"))
    is_archived_fallback: bool = False

    def __post_init__(self):
        if not self.title or not self.title.strip():
            raise ValueError("ArxivPaper title cannot be empty.")
        if not self.link or not self.link.startswith(("http://", "https://")):
            raise ValueError(f"Invalid link for ArxivPaper: {self.link}")
        if not self.summary or not self.summary.strip():
            raise ValueError("ArxivPaper summary cannot be empty.")


@dataclass
class ExecutiveBriefing:
    """Structured 3-bullet daily synthesis generated by Gemini LLM."""
    sector_events: str
    software_opensource: str
    ai_research: str
    generated_by_ai: bool = True
    disclaimer: str = ""


@dataclass
class PipelineReportResult:
    """Result payload returned by the master pipeline orchestrator."""
    date_str: str
    hn_items: list[TrendItem] = field(default_factory=list)
    github_items: list[GithubRepoItem] = field(default_factory=list)
    huggingface_items: list[HuggingFacePaperItem] = field(default_factory=list)
    arxiv_items: list[ArxivPaper] = field(default_factory=list)
    executive_briefing: Optional[ExecutiveBriefing] = None
    hn_status: SourceStatus = SourceStatus.SUCCESS
    github_status: SourceStatus = SourceStatus.SUCCESS
    huggingface_status: SourceStatus = SourceStatus.SUCCESS
    arxiv_status: SourceStatus = SourceStatus.SUCCESS
    ai_summary_status: SourceStatus = SourceStatus.SUCCESS
    report_file: Optional[Path] = None
    readme_updated: bool = False
    errors: list[str] = field(default_factory=list)

    @property
    def total_items_count(self) -> int:
        return (
            len(self.hn_items)
            + len(self.github_items)
            + len(self.huggingface_items)
            + len(self.arxiv_items)
        )

    @property
    def is_healthy(self) -> bool:
        """Returns True if the pipeline collected trends without critical errors."""
        return self.total_items_count > 0 and len(self.errors) == 0
